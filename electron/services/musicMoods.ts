const KEYS = Object.keys(MOODS).sort((a, b) => b.length - a.length)

export function normTag(tag: string): string {
  return tag.toLowerCase().replace(/\s+/g, ' ').trim()
}

export function moodOf(tag: string): MoodVector | null {
  const t = ` ${normTag(tag)} `
  for (const key of KEYS) {
    const at = t.indexOf(key)
    if (at < 0) continue
    const before = t[at - 1]
    const after = t[at + key.length]
    if (!/[a-z0-9]/.test(before) && !/[a-z0-9]/.test(after ?? ' ')) return MOODS[key]
  }
  return null
}

export function isGenre(tag: string): boolean {
  return moodOf(tag) != null
}
